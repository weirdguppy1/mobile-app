/** Case-insensitive substring filter on the university name. */
export function filterUniversities(query: string, limit = 50): University[] {
  const q = query.trim().toLowerCase();
  if (!q) return UNIVERSITIES.slice(0, limit);
  return UNIVERSITIES.filter((u) => u.name.toLowerCase().includes(q)).slice(0, limit);
}
